#!/usr/bin/env node
// Regenerates clips/manifest.js from the audio files in clips/. Run: node tools/clips-manifest.js
// (A GitHub Action does this automatically when you push files to clips/.)
const fs = require("fs"), path = require("path");
const dir = path.join(__dirname, "..", "clips");
const files = fs.readdirSync(dir)
  .filter(f => /\.(mp3|wav|ogg|m4a|aac|flac|webm)$/i.test(f))
  .sort();
const out = "// Generated by tools/clips-manifest.js. Do not edit by hand.\n" +
  "window.GV = window.GV || {};\nGV.clipFiles = " + JSON.stringify(files, null, 2) + ";\n";
fs.writeFileSync(path.join(dir, "manifest.js"), out);
console.log(files.length + " clip(s) listed");
